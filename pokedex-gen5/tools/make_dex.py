#!/usr/bin/env python3
"""Turn a name/type JSON into pokedex/dex_data.h.

    python3 tools/make_dex.py art/dex-1-649.json pokedex/dex_data.h

`art/dex-1-649.json` is the vendored slice of the public dataset at

    https://raw.githubusercontent.com/Purukitto/pokemon-data.json/master/pokedex.json

cut down to id / english name / types for 1..649 so the build does not need the
network and the repo does not carry 1.2 MB of stats nobody displays. Types are
the modern chart, which is what a viewer recognises (Charizard is Fire/Flying,
not plain Fire as in the 1996 Game Boy code).

Names are transliterated to ASCII because the panel renders Adafruit GFX fonts,
which have no glyph for ♀ or é and would draw a box instead: Nidoran♀ becomes
Nidoran-F, the way the official localisation writes it.
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

TYPES = {
    "Normal": "T_NORMAL", "Fire": "T_FIRE", "Water": "T_WATER",
    "Electric": "T_ELECTRIC", "Grass": "T_GRASS", "Ice": "T_ICE",
    "Fighting": "T_FIGHTING", "Poison": "T_POISON", "Ground": "T_GROUND",
    "Flying": "T_FLYING", "Psychic": "T_PSYCHIC", "Bug": "T_BUG",
    "Rock": "T_ROCK", "Ghost": "T_GHOST", "Dragon": "T_DRAGON",
    "Dark": "T_DARK", "Steel": "T_STEEL", "Fairy": "T_FAIRY",
}

MARKERS = {"♀": "-F", "♂": "-M", "\u2032": "'", "\u2019": "'", "e\u0301": "e"}


def ascii_name(name: str) -> str:
    for bad, good in MARKERS.items():
        name = name.replace(bad, good)
    # Anything else non-ASCII is decomposed and stripped: "Flabébé" -> "Flabebe".
    return unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode("ascii")


def main() -> None:
    src = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("pokedex/dex_data.h")
    rows = json.loads(src.read_text(encoding="utf-8"))
    rows = sorted(rows, key=lambda r: r["id"])
    count = rows[-1]["id"]
    if [r["id"] for r in rows] != list(range(1, count + 1)):
        raise SystemExit("ids are not 1..N contiguous")

    lines = [
        "// Generated by tools/make_dex.py from art/dex-1-649.json — do not edit.",
        "//",
        "// Name and types only: the panel shows the archive's own artwork, so no",
        "// sprite data lives here. 649 entries is the whole national dex up to",
        "// Genesect, which is what the archive ships.",
        "#pragma once",
        "",
        "struct DexEntry {",
        "  const char *name;",
        "  int8_t t1;            // primary type, index into TYPE_*",
        "  int8_t t2;            // secondary, or -1",
        "};",
        "",
        "static const DexEntry DEX[] = {",
    ]
    for r in rows:
        name = ascii_name(r["name"]["english"])
        types = r["type"]
        if not 1 <= len(types) <= 2:
            raise SystemExit(f"{name}: {len(types)} types")
        t1 = TYPES[types[0]]
        t2 = TYPES[types[1]] if len(types) > 1 else "-1"
        lines.append(f'  {{"{name}", {t1}, {t2}}},')
    lines.append("};")
    lines.append("static const int DEX_COUNT = (int)(sizeof(DEX) / sizeof(DEX[0]));")
    lines.append("")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")

    longest = max(len(ascii_name(r["name"]["english"])) for r in rows)
    print(f"{out}: {len(rows)} entries, longest name {longest} chars")


if __name__ == "__main__":
    main()
