#!/usr/bin/env python3
"""Turn the vendored species/move JSON into the firmware's 649-entry table.

``art/signature-moves.json`` is produced by ``tools/fetch_signatures.py`` and
holds, for every species, the move it actually uses in Black / White plus the
move's real type, base power and the damage Gen 5's formula gives against a
level-50 Ditto.

This script validates every move against the sketch's MOVE_LIST and every type
against the sketch's Type enum, then writes ``pokedex/signature_moves.h``. The
last column, ``hp``, is that damage scaled so one full pass over the 649 entries
spends Ditto's 100,000 HP exactly: the bar moves like the games (Hyper Beam takes
a bite, Sing takes nothing) and Ditto still faints on #649.

Usage:  python3 tools/make_signature.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

SRC = Path("art/signature-moves.json")
SKETCH = Path("pokedex/pokedex.ino")
OUT = Path("pokedex/signature_moves.h")
DITTO_HP_MAX = 100000
MOVE_RE = re.compile(r"X\((\w+),\s*(AF_\w+),\s*(T_\w+),")
TYPE_RE = re.compile(r"enum Type\s*:\s*\w+\s*\{([^}]*)\}")


def shares(damage: list[int], total: int) -> list[int]:
    """Split `total` in proportion to `damage`, exactly, by largest remainder."""
    scale = sum(damage)
    if scale <= 0:
        return [total // len(damage)] * len(damage)
    exact = [d * total / scale for d in damage]
    part = [int(e) for e in exact]
    left = total - sum(part)
    order = sorted(range(len(damage)),
                   key=lambda i: (-(exact[i] - part[i]), -damage[i], i))
    for i in order[:left]:
        part[i] += 1
    return part


def main() -> None:
    vocab = {m.group(1) for m in MOVE_RE.finditer(SKETCH.read_text())}
    types = set(re.findall(r"T_[A-Z]+", TYPE_RE.search(SKETCH.read_text()).group(1)))
    if not vocab or not types:
        raise SystemExit("could not parse MOVE_LIST / enum Type from pokedex.ino")
    data = json.loads(SRC.read_text())

    rows: list[tuple[str, str, int, int, int]] = []
    bad: list[str] = []
    fallback: list[str] = []
    damage: list[int] = []
    for pid in range(1, 650):
        entry = data.get(str(pid), {})
        move = entry.get("move", "")
        if move and move not in vocab:
            bad.append(f"{pid}:{entry.get('name', '?')}:{move}")
            move = ""
        tok = "T_" + (entry.get("move_type") or "").upper().replace("-", "")
        if tok not in types:
            tok = "T_NORMAL"
        if not move:
            fallback.append(f"{pid}:{entry.get('name', '?')}")
        damage.append(int(entry.get("damage", 0)))
        rows.append((move, tok, int(entry.get("power", 0)),
                     int(entry.get("damage", 0)), pid))

    hp = shares(damage, DITTO_HP_MAX)
    assert sum(hp) == DITTO_HP_MAX, "share table does not add up to Ditto's HP"
    body = "\n".join(
        f'  {{"{move}", {tok}, {power}, {dmg}, {h}}},'
        f'  // {pid} {data[str(pid)].get("name", "?")}'
        for (move, tok, power, dmg, pid), h in zip(rows, hp))

    if bad:
        print("moves with no effect in the sketch (falling back to pool):")
        print("  " + "\n  ".join(bad))
    OUT.write_text(
        "// Generated by tools/make_signature.py from art/signature-moves.json.\n"
        "//\n"
        "// One real Black/White level-up move per species. `type` is the move's\n"
        "// own type, `power` its base power in the games (0 = status), `damage`\n"
        "// Gen 5's formula against a level-50 Ditto (no crit, no roll), and `hp`\n"
        "// that damage scaled so the 649 entries spend Ditto's 100,000 exactly.\n"
        "#pragma once\n\n"
        "struct SigData {\n"
        "  const char *move;   // MOVE_LIST name; empty falls back to the type pool\n"
        "  uint8_t type;       // T_* of the move itself\n"
        "  uint8_t power;      // base power in the games (0 = status move)\n"
        "  uint16_t damage;    // Gen 5 damage vs a level-50 Ditto\n"
        "  uint16_t hp;        // share of Ditto's 100,000; sums to the pool\n"
        "};\n\n"
        "static const SigData SIG[DEX_COUNT] = {\n"
        f"{body}\n"
        "};\n"
    )
    print(f"{OUT}: 649 entries, {len(fallback)} empty move(s), "
          f"{len(bad)} bad name(s), {sum(1 for d in damage if d == 0)} zero-damage")
    print(f"Ditto HP shares: 0-{max(hp)}, total {sum(hp)}")


if __name__ == "__main__":
    main()
